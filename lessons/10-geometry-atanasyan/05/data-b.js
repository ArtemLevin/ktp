function poolFinal(mode,v){
  if(mode==='metrics'){
    const x=metricSets[v-1];
    return[
      T('Вариант '+v+'. Из точки S к плоскости α проведены SH⊥α и наклонная SA; SH='+x.sh+', HA='+x.ha+'. Найдите SA.',
        x.sa+'.','METRIC','В прямоугольном треугольнике SHA: SA=√('+x.sh+'²+'+x.ha+'²)='+x.sa+'.'),
      T('В той же конфигурации найдите sin φ, где φ — угол между SA и плоскостью α.',
        x.sh+'/'+x.sa+'.','LINE_PLANE_ANGLE','φ=∠SAH, поэтому sinφ=SH/SA='+x.sh+'/'+x.sa+'.'),
      T('Расстояние от точки S до плоскости α равно '+x.sh+'. Какой отрезок имеет эту длину?',
        'Перпендикуляр SH.','DISTANCE'),
      T('Что является ортогональной проекцией наклонной SA на плоскость α?',
        'Отрезок HA.','PROJ'),
      T('Сформулируйте роль теоремы о трёх перпендикулярах в метрической задаче.',
        'Она связывает перпендикулярность прямой в плоскости проекции наклонной с перпендикулярностью этой прямой самой наклонной.','THREE_PERP'),
      T('Две параллельные плоскости находятся на расстоянии '+x.gap+'. Какова длина любого общего перпендикуляра между ними?',
        x.gap+'.','DISTANCE'),
      T('Как строят линейный угол двугранного угла?',
        'Из одной точки ребра в каждой грани проводят луч, перпендикулярный ребру; угол между лучами является линейным.','DIHEDRAL'),
      T('Ошибка: угол между наклонной и произвольной прямой плоскости назвали углом наклонной с плоскостью.',
        'Нужно использовать угол наклонной с её ортогональной проекцией на плоскость.','ERROR'),
      T('Если SH='+x.sh+', SA='+x.sa+', чему равен cos угла между SA и плоскостью?',
        x.ha+'/'+x.sa+'.','ANGLE','cosφ=HA/SA='+x.ha+'/'+x.sa+'.'),
      T('Как проверить численный ответ для угла между прямой и плоскостью?',
        'Угол должен лежать в диапазоне от 0° до 90°; тригонометрическое отношение — от 0 до 1.','CHECK')
    ];
  }

  if(mode==='complex'){
    const x=complexSets[v-1],P=4*x.a,Sb=x.a*x.a,Slat=2*x.a*x.l,Sfull=Sb+Slat,V=Sb*x.h/3;
    const k=x.kNum/x.kDen,Ssec=Sb*k*k;
    return[
      T('Вариант '+v+'. Правильная четырёхугольная пирамида имеет сторону основания '+x.a+', высоту '+x.h+', апофему '+x.l+'. Найдите полную поверхность.',
        Sfull+'.','SURFACE','Sбок=1/2·'+P+'·'+x.l+'='+Slat+'; Sосн='+Sb+'; Sполн='+Sfull+'.'),
      T('Для той же пирамиды найдите объём.',
        V+'.','VOLUME','V=1/3·'+Sb+'·'+x.h+'='+V+'.'),
      T('Сечение параллельно основанию и имеет k='+x.kNum+'/'+x.kDen+'. Найдите площадь сечения.',
        fmt(Ssec)+'.','SECTION','Sсеч='+Sb+'·('+x.kNum+'/'+x.kDen+')²='+fmt(Ssec)+'.'),
      T('Какая величина используется в площади боковой поверхности, а какая — в объёме правильной пирамиды?',
        'В площади боковой поверхности — апофема; в объёме — пространственная высота.','MODEL'),
      T('Ошибка: в V=1/3·Sосн·h подставили апофему '+x.l+' вместо высоты '+x.h+'. Как исправить?',
        'Использовать h='+x.h+'; объём равен '+V+'.','ERROR'),
      T('Найдите отношение площади параллельного сечения к площади основания при k='+x.kNum+'/'+x.kDen+'.',
        (x.kNum*x.kNum)+'/'+(x.kDen*x.kDen)+'.','SIMILARITY'),
      T('Почему одна пространственная модель может требовать несколько рабочих плоскостей?',
        'Разные искомые величины могут лежать в разных плоских сечениях: апофема, диагональ, угол и сечение требуют собственного обоснованного плоского объекта.','PLANE'),
      T('Какой порядок действий уменьшает риск смешать поверхность и объём?',
        'Сначала назвать искомую величину и её размерность, затем выделить необходимые элементы и только после этого выбирать формулу.','STRATEGY'),
      T('Если все линейные размеры этой пирамиды увеличить в 2 раза, во сколько раз изменится объём?',
        'В 8 раз.','TRANSFER'),
      T('Как проверить комплексное решение независимо?',
        'Проверить каждую промежуточную длину/площадь, размерность финального ответа и, если возможно, решить один этап другим способом.','CHECK')
    ];
  }

  if(mode==='diagnostic'){
    const x=diagSets[v-1],a=x.letters[0],b=x.letters[1],sa=Math.hypot(x.sh,x.ha),vol=x.base*x.h,Nv=2+x.E-x.F;
    return[
      T('Вариант '+v+'. На проекции прямые '+a+' и '+b+' пересекаются. Можно ли только по рисунку утверждать, что они пересекаются в пространстве?',
        'Нет; требуется проверить принадлежность одной плоскости и общую точку в 3D-модели.','READ'),
      T('Прямые '+a+' и '+b+' не лежат в одной плоскости. Как их классифицировать?',
        'Скрещивающиеся.','REL'),
      T('Для доказательства c⊥α установлено только c⊥'+a+', где '+a+'⊂α. Достаточно ли этого?',
        'Нет; нужна ещё одна прямая плоскости α, пересекающая первую, и перпендикулярность c этой прямой.','COND'),
      T('SH='+x.sh+', HA='+x.ha+', SH⊥α, A∈α. Найдите SA и назовите рабочую плоскость.',
        fmt(sa)+'; плоскость SHA.','PLANE'),
      T('Какая проверка завершает построение многоугольника сечения?',
        'Он замкнут, каждая сторона лежит в конкретной грани, все вершины принадлежат секущей плоскости.','SECTION'),
      T('Призма имеет Sосн='+x.base+', h='+x.h+'. Найдите объём.',
        vol+'.','VOLUME'),
      T('Выпуклый многогранник имеет Ne='+x.E+', Nf='+x.F+'. Найдите Nv.',
        Nv+'.','EULER'),
      T('Подобные тела имеют k='+x.k+'. Во сколько раз отличаются площади поверхностей и объёмы?',
        (x.k*x.k)+' и '+(x.k*x.k*x.k)+'.','SIMILARITY'),
      T('Какой код ошибки соответствует неверно выбранной ортогональной проекции?',
        'PROJ.','PROJ'),
      T('Какой финальный код ставится, если вычисления не проверены по единицам и геометрическому смыслу?',
        'CHECK.','CHECK')
    ];
  }

  if(mode==='correction'){
    const x=diagSets[v-1],sa=Math.hypot(x.sh,x.ha),vol=x.base*x.h;
    return[
      T('Вариант '+v+'. Ученик увидел на проекции прямой угол и сразу записал теорему Пифагора. Код ошибки и первый шаг коррекции?',
        'READ/COND: прямой угол должен следовать из условия или быть доказан; сначала восстановить это основание.','READ'),
      T('Для c⊥α доказано c⊥a, a⊂α, и больше ничего. Код ошибки?',
        'COND: не проверена перпендикулярность второй пересекающейся прямой плоскости.','COND'),
      T('SH='+x.sh+', HA='+x.ha+', но ученик назвал SA='+fmt(sa)+' проекцией наклонной на плоскость. Код и исправление?',
        'PROJ: проекция наклонной SA — отрезок HA.','PROJ'),
      T('При построении сечения две точки на разных гранях соединены напрямую. Код и исправление?',
        'SECTION: сначала нужно получить допустимый след на грани; сторону сечения можно строить только в конкретной грани.','SECTION'),
      T('Призма имеет Sосн='+x.base+', h='+x.h+', боковое ребро '+(x.h+4)+'. Ученик использовал боковое ребро в формуле объёма. Код и правильный объём?',
        'VOLUME/COND; использовать h='+x.h+', V='+vol+'.','VOLUME'),
      T('Получен угол 118° между прямой и плоскостью. Код и исправление?',
        'CHECK: такой угол берут в диапазоне 0°–90°; нужно перепроверить рабочий треугольник и выбранный угол.','CHECK'),
      T('В доказательстве есть переход «отсюда плоскости параллельны» без ссылки на признак. Код?',
        'LOGIC: нужно указать теорему или признак и проверить его условия.','LOGIC'),
      T('При k='+x.k+' площадь поверхности умножили на '+x.k+'. Код и исправление?',
        'METRIC/SURFACE: площадь масштабируется как k², то есть в '+(x.k*x.k)+' раз.','SURFACE'),
      T('Каков полный цикл адресной коррекции после определения кода ошибки?',
        'Минимальное правило → корректный пример → близкая задача → задача переноса → короткий ретест.','RETEST'),
      T('Что переносится в 11 класс без введения новых формул на этом уроке?',
        'Навык чтения 3D-модели, выбора рабочей плоскости, проверки проекции, условий теорем и размерности.','BRIDGE')
    ];
  }
  return[];
}

function example(title,t,scene){
  return{
    title,
    problem:t.text,
    idea:'Сначала распознать домен ошибки или тип величины, затем выбрать минимально достаточный метод.',
    solution:t.solution||t.answer,
    check:'Проверить условия метода, размерность и геометрический смысл результата.',
    answer:t.answer,
    spatialFigure:scene
  };
}

function assessment(mode,kind){
  const independent=kind==='independent';
  const max=independent?10:14;
  const count=independent?5:6;
  const points=independent?[2,2,2,2,2]:[2,2,2,2,2,4];
  return{
    title:independent?'Самостоятельная работа':'Поурочный контроль',
    purpose:independent?'Проверить выбор метода и ключевой навык урока.':'Проверить модель, условия метода, вычисления, диагностику и проверку.',
    duration:independent?'12–15 минут':'20–25 минут',
    maxScore:max,
    grading:grading(max),
    variants:Array.from({length:6},(_,i)=>({
      id:i+1,
      tasks:poolFinal(mode,i+1).slice(0,count).map((q,j)=>({...q,points:points[j]}))
    }))
  };
}

