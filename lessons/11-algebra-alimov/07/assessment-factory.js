function variants(type,kind){
  const out=[];
  for(let v=1;v<=6;v++){
    let tasks=base(type,v);
    if(kind==='control')tasks=tasks.concat([
      T(`Вариант ${v}: найдите и исправьте типичную ошибку в рассуждении по теме урока.`,'Нужно указать ошибочный шаг, условие применимости и корректное исправление.',2,'Анализ ошибки'),
      T(`Вариант ${v}: запишите способ быстрой самопроверки ответа.`,'Подстановка, проверка ОДЗ, знака, диапазона или независимый способ, подходящий к задаче.',2,'Самопроверка')]);
    tasks=tasks.map((t,i)=>({...t,points:kind==='control'?[1,1,2,2,3,3][i]:[1,2,2,3][i]}));
    out.push(V(v,tasks));
  }
  return out;
}
