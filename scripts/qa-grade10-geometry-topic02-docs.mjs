import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
let checks=0;const assert=(v,m)=>{checks++;if(!v)throw new Error(m)};
const metric=(text,label)=>{
  const i=text.indexOf(label);if(i<0)return NaN;
  const chunk=text.slice(i,i+180);
  const m=chunk.match(/\*\*(\d+)\*\*/)||chunk.match(/(\d+)/);
  return m?Number(m[1]):NaN;
};
const R=read('README.md'),P=read('Plan.md'),L=read('lessons/README.md'),A=read('assessments/README.md'),M=read('content/10-geometry-atanasyan/content-map.md');
assert(metric(R,'Суммарно опубликовано')>=1077,'README lesson aggregate must not regress');
assert(R.match(/(?:78|79|8\d|9\d|1\d\d) тематических assessment-комплект/),'README assessment aggregate must not regress');
for(const token of ['10-geometry-atanasyan','02-methodical-plan.md','parallel-space/','Тема 02 **«Параллельность прямых и плоскостей»** полностью реализована'])assert(R.includes(token),`README missing ${token}`);
assert(metric(P,'полностью готовых тематических серий:')>=78,'Plan series metric must not regress');
assert(metric(P,'опубликованных уроков:')>=1077,'Plan lesson metric must not regress');
assert(metric(P,'тематических assessment-комплектов:')>=78,'Plan assessment metric must not regress');
assert(P.includes('Тема 02 **«Параллельность прямых и плоскостей»** полностью реализована'),'Plan topic02');
assert(L.includes('Серия `02` **«Параллельность прямых и плоскостей»**'),'lessons topic02');
assert(metric(L,'Всего опубликовано')>=1077,'lessons aggregate must not regress');
assert(L.includes('parallel-space/'),'lessons lab');
assert(A.includes('Комплект `02`'),'assessment topic02');
assert(metric(A,'Всего опубликовано')>=78,'assessment aggregate must not regress');
for(const token of ['6×7 / 14 баллов','6×10 / 20 баллов'])assert(A.includes(token),`assessments missing ${token}`);
const row=M.split('\n').find(x=>x.includes('| 02 | Параллельность прямых и плоскостей |'));
assert(row&&row.endsWith('| full |'),'content map topic 02 must stay full');
console.log(`Grade 10 Atanasyan topic 02 documentation QA passed: ${checks} checks.`);
